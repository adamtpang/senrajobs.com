import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { compileRoles, compileCompanies } from '../board-data.mjs';

const role = { title: 'Engineer', url: 'https://example.com/job', location: 'Remote' };
const guests = ['First founder', 'Second founder'].map(name => ({ name, episode: { url: 'https://example.com/episode' }, companies: [{ name: 'Company', careers: 'https://example.com/careers' }] }));
const merged = compileRoles(guests, { Company: { fetched: '2026-10-04T00:00:00Z', roles: [role, role, { ...role, url: 'javascript:alert(1)' }] } });
assert.equal(merged.length, 1, 'Duplicate or unsafe job URLs must not enter the board');
assert.equal(merged[0].founders.length, 2, 'Deduplication must preserve both founders');
const companyRows = compileCompanies(guests, merged);
assert.equal(companyRows.length, 1, 'Shared companies must appear once');
assert.equal(companyRows[0].guests.length, 2, 'Company rows must preserve guest relationships');
assert.equal(companyRows[0].roles.length, 1, 'Company rows must use deduplicated roles');
const sharedGuests=[{name:'Studio founder',companies:[{name:'Studio',careers:'https://example.com/studio'}]},{name:'Parent CEO',companies:[{name:'Parent (CEO)',careers:'https://example.com/parent'}]}];
const sharedRoles=compileRoles(sharedGuests,{Studio:{roles:[role]},'Parent (CEO)':{roles:[role]}});
assert.equal(sharedRoles.length,1);assert.equal(sharedRoles[0].founders.length,2);
assert.deepEqual(sharedRoles[0].companyAssociations,['Studio','Parent (CEO)']);
assert.ok(compileCompanies(sharedGuests,sharedRoles).every(c=>c.roles.length===1),'A shared role must remain reachable under both the studio and its parent');
assert.equal(compileCompanies([{name:'Founder',companies:[{name:'Closed company',note:'acquired or closed'}]}],[]).length,0, 'Closed company associations must stay out of browsing');
assert.equal(compileRoles(guests, { Company: { roles: [], fetched: '2026-10-04' } }).length, 0);

const html = fs.readFileSync('index.html', 'utf8');
assert.ok(!/__BOARD_|__GUESTS__|__ROLES__|__ROLE_DATA__|__COMPANY_DATA__|__GUEST_DATA__|__NO_SCRIPT__|__COVERAGE_DATA__/.test(html), 'Build placeholders must be resolved');
assert.ok(html.includes('<script data-board-controls>') && !html.includes('src="/board.js"'), 'Controls must ship with their matching page data');
new vm.Script(html.match(/<script data-board-controls>([\s\S]*?)<\/script>/)[1]);
const data = compileRoles(JSON.parse(fs.readFileSync('guests.json', 'utf8')), JSON.parse(fs.readFileSync('jobs.json', 'utf8')));
assert.ok(data.length > 0);
assert.equal(new Set(data.map(r => r.url)).size, data.length);
assert.ok(data.every(r => r.founders.length && r.careers && Number.isFinite(Date.parse(r.fetched))));
assert.ok(html.includes('data-guest=')&&html.includes('id="companies-list"')&&html.includes('id="aggregate"'), 'Guest links must preserve the company-to-role browsing path');
assert.equal((html.match(/class="founder"/g) || []).length, JSON.parse(fs.readFileSync('guests.json', 'utf8')).length);
const embeddedRoles = JSON.parse(html.match(/<script id="role-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.deepEqual(embeddedRoles.map(role=>role.url).sort(),data.map(role=>role.url).sort(), 'Every indexed role must remain available to role browsing');
assert.ok(!html.includes('details class="founder"') && !html.includes('details class="co"'), 'Guest and company navigation must not use nested expansion');
const embeddedCompanies = JSON.parse(html.match(/<script id="company-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.ok(embeddedCompanies.every(company=>company.note!=='acquired or closed'));
assert.equal(new Set(embeddedCompanies.map(company=>company.name)).size,embeddedCompanies.length);
console.log(`Board checks passed: ${data.length} unique roles with founder context.`);
