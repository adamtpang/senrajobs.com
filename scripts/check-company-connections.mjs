import assert from 'node:assert/strict';
import fs from 'node:fs';
import {applyCompanyConnections} from '../company-connections.mjs';
import {compileRoles,compileCompanies} from '../board-data.mjs';
import {clientRole} from '../client-data.mjs';
import {discoveryReports} from '../discovery-reports.mjs';
const fixture=()=>[{name:'Author',episode:{url:'https://example.com/episode'},companies:[{name:'Company (episode subject)',careers:'https://example.com/jobs'}]},{name:'Founder',episode:{url:'https://example.com/other'},companies:[{name:'Company',careers:'https://example.com/jobs'}]}];
const connection={guest:'Author',company:'Company',type:'episode-subject',subject:'Subject',source:'https://example.com/episode',companySource:'https://example.com/company',checkedOn:'2026-10-19'};
const guests=applyCompanyConnections(fixture(),[connection]);
const board={fetched:'2026-10-19T20:00:00Z',roles:[{title:'Builder',url:'https://example.com/job',location:'Austin, TX',sourceStatus:'current'}],coverage:{status:'complete'}};
const jobs={'Company (episode subject)':board,Company:board};
const roles=compileRoles(guests,jobs);
assert.equal(roles.length,1);assert.equal(roles[0].founders.length,2);
assert.equal(roles[0].founders.find(f=>f.name==='Author').connection.subject,'Subject');
assert.equal(roles[0].founders.find(f=>f.name==='Founder').connection,undefined);
assert.equal(clientRole(roles[0]).founders[0].connection.source,connection.source);
const companies=compileCompanies(guests,roles);assert.equal(companies.length,1);assert.equal(companies[0].connections[0].guest,'Author');
assert.equal(discoveryReports(guests,jobs,roles).coverage.companies[0].connections[0].subject,'Subject');
assert.throws(()=>applyCompanyConnections(fixture(),[{...connection,company:'Missing'}]),/no matching/);
assert.throws(()=>applyCompanyConnections(fixture(),[{...connection,source:'https://example.com/wrong'}]),/this guest/);
assert.throws(()=>applyCompanyConnections(fixture(),[connection,connection]),/Duplicate/);
const actual=JSON.parse(fs.readFileSync('guests.json','utf8'));
assert.equal(actual.filter(g=>g.name==='Eric Jorgenson').length,1);
const elonCompanies=actual.find(g=>g.name==='Eric Jorgenson').companies.filter(c=>c.connection?.subject==='Elon Musk');
assert.deepEqual(elonCompanies.map(c=>c.name.split(' (')[0]).sort(),['Tesla','SpaceX / Starlink','Neuralink','xAI / X','The Boring Company','PayPal','Zip2'].sort());
assert.equal(elonCompanies.find(c=>c.name.startsWith('Zip2')).careers,undefined,'Historical acquisition must not become a parent-wide jobs link');
assert.match(elonCompanies.find(c=>c.name.startsWith('PayPal')).name,/historical co-founder/);
assert.ok(!actual.some(g=>g.name==='Elon Musk'),'An episode subject must not become a fictional interview guest');
console.log('Company connection provenance, deduplication, invalid mappings and actual registry checks pass.');
