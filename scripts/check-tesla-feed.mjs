import assert from 'node:assert/strict';
import {parseTeslaBrowserReceipt,mergeTeslaBrowserReceipts,teslaDetailContent} from '../tesla-feed.mjs';
const row=(index,id,city='Austin')=>({index,url:`https://www.tesla.com/careers/search/job/engineer-${id}`,text:`Engineer\nEngineering & Information Technology ・ Full-Time\n${city}, Texas\nLearn More`});
const r={source:'https://www.tesla.com/careers/search/?site=US&state=TX',filters:{site:'US',state:'TX'},total:2,rows:[row(0,10),row(1,20)],observedAt:'2026-10-26T18:00:00Z',steps:[{y:0,first:0,last:1}],method:'Rendered public rows'};
assert.equal(parseTeslaBrowserReceipt(r).complete,true);
assert.equal(mergeTeslaBrowserReceipts([r]).coverage.status,'partial');
assert.equal(parseTeslaBrowserReceipt({...r,rows:[r.rows[1]]}).complete,false);
assert.throws(()=>parseTeslaBrowserReceipt({...r,rows:[r.rows[0],r.rows[0]]}),/duplicate/);
assert.throws(()=>parseTeslaBrowserReceipt({...r,steps:[]}),/receipts/);
assert.throws(()=>parseTeslaBrowserReceipt({...r,steps:[{y:0,first:1,last:1}]}),/no scroll/);
assert.throws(()=>parseTeslaBrowserReceipt({...r,rows:[{...r.rows[0],url:'https://other.example/engineer-10'}]}),/Invalid Tesla/);
assert.throws(()=>parseTeslaBrowserReceipt({...r,filters:{site:'US',state:'CA'}}),/filter/);
assert.equal(parseTeslaBrowserReceipt({...r,rows:[row(0,10),row(1,10,'Dallas')]}).rows[0].locations.length,2);
const global={...r,source:'https://www.tesla.com/careers/search/',filters:0};
assert.equal(mergeTeslaBrowserReceipts([global]).coverage.status,'complete');
const unknown={...global,rows:[{...r.rows[0],text:'Engineer\nEngineering & Information Technology ・ Full-Time\nLearn More'},r.rows[1]]};
assert.equal(parseTeslaBrowserReceipt(unknown).rows[0].locationStatus,'unknown');
assert.equal(mergeTeslaBrowserReceipts([unknown]).coverage.listingStatus,'complete');
assert.equal(mergeTeslaBrowserReceipts([unknown]).coverage.status,'partial');
assert.equal(mergeTeslaBrowserReceipts([unknown]).coverage.unknownLocations,1);
assert.equal(parseTeslaBrowserReceipt({...global,rows:[{...r.rows[0],url:'https://www.tesla.com/careers/search/job/-10'},r.rows[1]]}).rows[0].id,'10');
const role=parseTeslaBrowserReceipt(r).rows[0],detail={title:'Engineer',observedAt:r.observedAt,fields:[['Req. ID','10']],text:'What You’ll Bring\nSoftware experience'};
assert.equal(teslaDetailContent(role,detail).source,role.url);
assert.throws(()=>teslaDetailContent(role,{...detail,fields:[['Req. ID','20']]}),/mismatch/);
assert.throws(()=>teslaDetailContent(role,{...detail,title:'Wrong role'}),/mismatch/);
console.log('Tesla: scope, row continuity, source URLs, duplicate identity and location merging checks pass.');
