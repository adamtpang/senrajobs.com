import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseCulinaryCards,parseCulinaryDetail} from '../culinary-feed.mjs';
import {sourceIdentityMatches} from '../ats.mjs';
import {formatPublishedPay} from '../job-utils.mjs';
const root='.cache/mfg-2026-10-26/';
const cards=parseCulinaryCards(fs.readFileSync(root+'search-response.txt','utf8'));
const browser=JSON.parse(fs.readFileSync(root+'list.json'));
assert.deepEqual(cards.map(c=>c.url).sort(),browser.cards.map(c=>c.url).sort());
const html=fs.readFileSync(root+'detail-sample.html','utf8');
const card=cards.find(c=>c.id==='733710');
const role=parseCulinaryDetail(html,card,'2026-10-26T22:00:00Z');
assert.equal(role.location,'New York, NY, US');assert.equal(role.payRanges[0].min,75000);assert.equal(role.payRanges[0].currency,'USD');assert.equal(role.payRanges[0].period,'year');
assert.throws(()=>parseCulinaryDetail(html,{...card,url:cards[1].url},'2026-10-26T22:00:00Z'),/identity/);
assert.throws(()=>parseCulinaryCards('({"html":"","length":1});'),/count/);
assert(sourceIdentityMatches({kind:'culinary-public',slug:'majorfood'},'Major Food Group'));
assert(!sourceIdentityMatches({kind:'culinary-public',slug:'majorfood'},'Another company'));
const tipped=parseCulinaryDetail(html,{...card,publishedCompensation:'Full/Part Time / Hourly ($17) plus tips'},'2026-10-26T22:00:00Z');
assert.equal(tipped.employmentType,'Full/Part Time');assert(formatPublishedPay(tipped).endsWith('+ tips'));
console.log(`${cards.length} official browser cards reconciled; detail identity, location, pay and employer boundaries pass.`);
