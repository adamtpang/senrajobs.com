import assert from 'node:assert/strict';
import fs from 'node:fs';
import {associationEvidence} from '../association-evidence.mjs';
const guests=[{name:'Guest',companies:[{name:'Current'},{name:'Previous (former executive)'}]}];
const record={guest:'Guest',company:'Current',relationship:'founder',reviewedOn:'2026-10-27',claim:'The official source identifies this guest as founder.',sources:[{url:'https://example.com/about',supports:'Founder biography.'}]};
const audit=associationEvidence(guests,[record]);
assert.equal(audit.summary.reviewed,1);assert.equal(audit.summary.pending,1);
assert.equal(audit.get('Guest','Previous (former executive)').status,'pending');
assert.equal(audit.summary.exhaustiveEmployerCensusVerified,false);
assert.throws(()=>associationEvidence(guests,[record,record]),/Duplicate/);
assert.throws(()=>associationEvidence(guests,[{...record,company:'Previous'}]),/exact registry/);
assert.throws(()=>associationEvidence(guests,[{...record,sources:[]}]),/Invalid association sources/);
assert.throws(()=>associationEvidence(guests,[{...record,sources:[{url:'https://user:secret@example.com',supports:'Claim'}]}]),/Invalid association sources/);
const full=associationEvidence([guests[0],{name:'Second',companies:[{name:'Current'}]}],[record]);
assert.equal(full.summary.registryRows,3,'Shared company relationships must remain separate by guest.');
const real=associationEvidence(JSON.parse(fs.readFileSync('guests.json')),JSON.parse(fs.readFileSync('employer-associations.json')));
assert.ok(real.summary.reviewed>0);assert.ok(real.summary.pending>=0);
const reconciled=associationEvidence([{name:'Guest',companies:[{name:'Current'}]}],[record]);
assert.equal(reconciled.summary.pending,0);
assert.equal(reconciled.summary.allRecordedAssociationsHaveReviewedEvidence,true);
assert.equal(reconciled.summary.exhaustiveEmployerCensusVerified,false,'Reviewing the registry must not certify undiscovered employers.');
console.log(JSON.stringify({result:'PASS relationship evidence validation',...real.summary}));
