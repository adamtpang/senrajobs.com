import assert from 'node:assert/strict';
import {ATOMS_CHANNELS,atomsPlainText,parseAtomsChannel,reconcileAtomsRows,fetchAtoms,selectAtomsBrand} from '../atoms-feed.mjs';
import {mapATSJob,retainBoard} from '../ats.mjs';
const at='2026-10-27T19:00:00.000Z';
function job(slug,id,internal=12,description='Requires Python. Work with customers.',location='Austin, TX',brand='Otter'){
 return {id,internal_job_id:internal,title:'Solutions Engineer',absolute_url:`https://job-boards.greenhouse.io/${slug}/jobs/${id}`,location:{name:location},company_name:'Published employer',content:`&lt;p&gt;${description}&lt;/p&gt;`,metadata:[{name:'Brand',value:brand},{name:'Division',value:'Engineering'},{name:'FADV_Package',value:'not-returned'}],departments:[],offices:[]};
}
const board=(jobs,total=jobs.length)=>({jobs,meta:{total}});
const channel=slug=>ATOMS_CHANNELS.find(c=>c.slug===slug);
const parse=(slug,data)=>parseAtomsChannel(data,channel(slug),at,mapATSJob);
assert.equal(atomsPlainText('&amp;lt;p&amp;gt;A&#160;&amp;amp; B&amp;lt;/p&amp;gt;'),'A & B');
const css=parse('cssmerge',board([job('cssmerge',1)]));
const otter=parse('otter',board([job('otter',2)]));
assert.equal(css.status,'complete');assert.equal(css.rows[0].employerBrand,'Otter');
assert.ok(!JSON.stringify(css.rows[0]).includes('FADV_Package'));
const mirrors=reconcileAtomsRows([...css.rows,...otter.rows],{preferredUrls:[otter.rows[0].url]});
assert.equal(mirrors.rows.length,1);assert.equal(mirrors.rows[0].url,otter.rows[0].url);assert.deepEqual(mirrors.rows[0].alternateUrls,[css.rows[0].url]);
assert.deepEqual(mirrors.rows[0].sourceBoards,['cssmerge','otter']);
const spaced=job('atoms',13);spaced.title=' Solutions Engineer ';
assert.equal(reconcileAtomsRows([...css.rows,...parse('atoms',board([spaced])).rows]).rows.length,1);
const changed=parse('atoms',board([job('atoms',3,12,'Requires ten years of Python.')])).rows;
const differentLocation=parse('lab37',board([job('lab37',4,12,undefined,'Pittsburgh, PA')])).rows;
assert.equal(reconcileAtomsRows([...css.rows,...changed,...differentLocation]).rows.length,3);
assert.equal(reconcileAtomsRows([...css.rows,...changed,...differentLocation]).identityVariants.length,1);
const mixed=parse('atoms',board([job('atoms',5,12,undefined,undefined,'Atoms')])).rows;
assert.equal(reconcileAtomsRows([...css.rows,...mixed]).rows[0].employerBrandAmbiguous,true);
assert.deepEqual(reconcileAtomsRows([...css.rows,...mixed]).rows[0].employerBrands,['Atoms','Otter']);
const absent=job('atoms',6);absent.metadata=[];assert.equal(parse('atoms',board([absent])).rows[0].employerBrandSource,'unknown');
const invalid=job('cssmerge',7);invalid.absolute_url='https://evil.example/cssmerge/jobs/7';
assert.equal(parse('cssmerge',board([invalid])).status,'partial');assert.equal(parse('cssmerge',board([invalid])).rows.length,0);
assert.equal(parse('cssmerge',board([job('cssmerge',8)],2)).status,'partial');
assert.equal(parse('cssmerge',{jobs:[]}).status,'partial');assert.equal(parse('cssmerge',board([])).status,'complete');
assert.equal(parse('cssmerge',board([job('cssmerge',8),job('cssmerge',8)])).status,'partial');
const noDescription=job('atoms',9);noDescription.content='';assert.equal(parse('atoms',board([noDescription])).status,'partial');
const fetched=await fetchAtoms({observedAt:at,mapJob:mapATSJob,request:async url=>{
 const slug=new URL(url).pathname.split('/')[3];
 if(slug==='otter')throw Error('Temporary timeout');
 return {ok:true,data:board(slug==='cssmerge'?[job(slug,1)]:[])};
}});
assert.equal(fetched.status,'partial');assert.ok(!fetched.completedPublicBoards.includes('otter'));
const previous={roles:[{url:'https://job-boards.greenhouse.io/otter/jobs/998',title:'Previous Otter role'},{url:'https://job-boards.greenhouse.io/atoms/jobs/997',title:'Closed on exhausted source'}]};
const retained=retainBoard(previous,fetched,at);
assert.ok(retained.roles.some(r=>r.url===previous.roles[0].url&&r.sourceStatus==='retained-previous'));
assert.ok(!retained.roles.some(r=>r.url===previous.roles[1].url));
const failed=await fetchAtoms({observedAt:at,mapJob:mapATSJob,request:async()=>({ok:false,error:'offline'})});
assert.equal(failed.status,'failed');assert.deepEqual(failed.completedPublicBoards,[]);
assert.equal(retainBoard(previous,failed,at).roles.length,2);
assert.equal(selectAtomsBrand(fetched,'Otter').rows.length,1);
assert.equal(selectAtomsBrand(fetched,'ProFood Properties').rows.length,0);
assert.equal(selectAtomsBrand(fetched,'ProFood Properties').status,'partial');
assert.throws(()=>selectAtomsBrand(fetched,'Other investor portfolio'));
console.log('Atoms source identity, exact mirror, ambiguity, brand, empty/partial source and previous-role retention checks passed.');
